#!/usr/bin/env python3
"""Exercise the installed hook in a temporary repository."""

from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


class CommitPolicyTest(unittest.TestCase):
    def test_hook(self):
        cases = [
            ("Improve pricing accuracy", True),
            ("Fix airflow calculation", True),
            ("Исправить расчёт", False),
            ("Improve pricing\n\nОписание", False),
            ("Improve pricing\n\nCo-Authored-By: Person <test@example.invalid>", False),
            ("Generated by OpenAI", False),
            ("Use codex", False),
            ("Mention Claude", False),
            ("Mention Anthropic", False),
            ("Use ChatGPT", False),
            ("Generated with AI", False),
            ("12345", False),
            ("", False),
        ]
        with tempfile.TemporaryDirectory(prefix="commit-policy-") as temp:
            repo = Path(temp)
            subprocess.run(["git", "init", "-q", str(repo)], check=True)
            shutil.copytree(ROOT / ".githooks", repo / ".githooks")
            (repo / "scripts").mkdir()
            shutil.copy(ROOT / "scripts/check_commit_message.py", repo / "scripts")
            subprocess.run(
                ["git", "-C", str(repo), "config", "core.hooksPath", ".githooks"],
                check=True,
            )
            message_file = repo / "message.txt"
            for message, accepted in cases:
                with self.subTest(message=message):
                    message_file.write_text(message, encoding="utf-8")
                    result = subprocess.run(
                        [str(repo / ".githooks/commit-msg"), str(message_file)],
                        cwd=repo, capture_output=True, text=True,
                    )
                    self.assertEqual(result.returncode, 0 if accepted else 1, result.stderr)
            message_file.unlink()
            missing = subprocess.run(
                [str(repo / ".githooks/commit-msg"), str(message_file)],
                cwd=repo, capture_output=True,
            )
            self.assertEqual(missing.returncode, 2)
            subprocess.run(["git", "-C", str(repo), "config", "user.name", "Test User"], check=True)
            subprocess.run(["git", "-C", str(repo), "config", "user.email", "test@example.invalid"], check=True)
            subprocess.run(
                ["git", "-C", str(repo), "commit", "--allow-empty", "-m", "Verify commit hook installation"],
                check=True, capture_output=True,
            )


if __name__ == "__main__":
    unittest.main()
